/** The series of a report: item name → SDMX key (`generate_bps_series_ids`). Reports other than main and summary are quarterly only. */
export function bpsSeriesIds(frequency: 'monthly' | 'quarterly', reportType: BpsReportType, country?: string): Record<string, string> {
  const freq = (reportType === 'main' || reportType === 'summary') && !country ? (frequency === 'monthly' ? 'M' : 'Q') : 'Q'
  const area = country ? BPS_COUNTRIES[country] : undefined
  const entries = area !== undefined ? SERIES.country! : SERIES[reportType]!
  return Object.fromEntries(Object.entries(entries).map(([name, tail]) => [name, `${freq}.${tail.replace('{c}', area ?? '')}`]))
}
