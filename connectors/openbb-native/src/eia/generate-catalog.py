"""Regenerate src/eia/catalog.json and src/eia/constants.ts from the openbb_us_eia package (OpenBB Platform 5.0.0, Apache-2.0).

    ~/.venvs/openbb/bin/python -I src/eia/generate-catalog.py

The dataset catalog (openbb_us_eia/assets/eia_catalog.json.xz) is the registry the package builds its ~200 dataset
models from. This keeps what the runtime reads (api_query.py, catalog.py): per dataset the API path, the frequencies and
their period formats, the data columns, and the facets with their value vocabularies. Vocabularies are [value, slug]
pairs held once in `pool`; descriptions, labels and unit texts only feed OpenBB's generated documentation and are
dropped. `routes` maps every OpenBB route the provider answers to its (group, dataset) as eia_router.py registers it.
"""

import json
import sys
from pathlib import Path

from openbb_us_eia.models import registry
from openbb_us_eia.models.ieo import EiaIeoQueryParams
from openbb_us_eia.models.aeo import EiaAeoQueryParams
from openbb_us_eia.utils import catalog, constants

HERE = Path(__file__).parent
CATEGORIZED = {"petroleum", "natural_gas"}  # eia_router.py nests these under the EIA category

groups = catalog.load_catalog()
pool: list[list[list[str]]] = []
pool_index: dict[str, int] = {}


def pooled(choices: list[dict]) -> int:
    pairs = [[c["value"], c["param"]] for c in choices]
    key = json.dumps(pairs, separators=(",", ":"))
    if key not in pool_index:
        pool_index[key] = len(pool)
        pool.append(pairs)
    return pool_index[key]


out_groups: dict = {}
for group_name, group in groups.items():
    datasets: dict = {}
    for slug, spec in group["datasets"].items():
        facets: dict = {}
        for canonical, detail in spec["facets"].items():
            facet: dict = {"id": detail["id"]}
            if detail.get("choices"):
                facet["choices"] = pooled(detail["choices"])
            if detail.get("frequencies"):
                facet["frequencies"] = detail["frequencies"]
            if detail.get("filterable", True) is False:
                facet["filterable"] = False
            facets[canonical] = facet
        datasets[slug] = {
            "path": spec["path"],
            "start": spec.get("start_period"),
            "end": spec.get("end_period"),
            "frequency": spec.get("default_frequency"),
            "frequencies": {f: [d["format"], d["path"]] for f, d in spec["frequencies"].items()},
            "columns": {name: [d["id"], 1 if d.get("numeric", True) else 0] for name, d in spec["data_columns"].items()},
            "facets": facets,
        }
    out_groups[group_name] = {
        "choices": {facet: pooled(choices) for facet, choices in group["choices"].items()},
        "datasets": datasets,
    }

routes: dict = {}
for group_name, group in groups.items():
    for slug, spec in group["datasets"].items():
        if group_name in catalog.DATASET_GROUPS:
            category = spec.get("category_slug")
            parts = ["eia", group_name] + ([category] if group_name in CATEGORIZED and category else []) + [slug]
            routes["/".join(parts).replace("//", "/")] = [group_name, slug]
# The single-model groups: one route each; AEO and IEO pick the dataset (release) from a parameter.
for name in ("crude_oil_imports", "international", "seds", "total_energy"):
    routes[f"eia/{name}"] = [name, name]
routes["eia/aeo"] = ["aeo", None, EiaAeoQueryParams.model_fields["release"].default]
routes["eia/ieo"] = ["ieo", None, EiaIeoQueryParams.model_fields["release"].default]

(HERE / "catalog.json").write_text(json.dumps({"pool": pool, "groups": out_groups, "routes": dict(sorted(routes.items()))}, separators=(",", ":")) + "\n")

# The 3 hand-written models (petroleum status report, short-term energy outlook) keep their tables in constants.py.
def ts(value) -> str:
    return json.dumps(value, indent=2, ensure_ascii=False)


lines = [
    "// Generated by src/eia/generate-catalog.py from openbb_us_eia/utils/constants.py (OpenBB Platform 5.0.0, Apache-2.0).",
    "// The Weekly Petroleum Status Report workbooks and tables, and the Short-Term Energy Outlook tables and series.",
    "",
    f"export const WPSR_FILE_MAP: Record<string, string> = {ts(constants.WpsrFileMap)}",
    "",
    f"/** Category → table → sheet name. */\nexport const WPSR_TABLE_MAP: Record<string, Record<string, string>> = {ts(constants.WpsrTableMap)}",
    "",
    f"export const STEO_TABLE_NAMES: Record<string, string> = {ts(constants.SteoTableNames)}",
    "",
    "/** Table → series ids, in the order OpenBB presents them. */",
    "export const STEO_TABLE_MAP: Record<string, string[]> = {",
]
for table, symbols in constants.SteoTableMap.items():
    lines.append(f"  {json.dumps(table)}: {json.dumps(symbols, ensure_ascii=False)},")
lines.append("}")
(HERE / "constants.ts").write_text("\n".join(lines) + "\n")

print(len(routes), "routes;", len(pool), "pooled vocabularies", file=sys.stderr)
